// Builds src/price-list.js from the studio price grid (CSV).
// Usage: node scripts/generate-pricing.mjs [path-to-csv]
// Prices are final customer prices in RON (the studio is not VAT registered).
import { readFileSync, writeFileSync } from 'node:fs';
import { parseCsv } from './csv.mjs';

const source =
  process.argv[2] ?? 'Elite_Custom_Wrap_Grila_Preturi_Finala_v2.csv';
const rows = parseCsv(readFileSync(source, 'utf8').replace(/^\uFEFF/, ''));
const header = rows.shift().map((value) => value.trim());
const column = (name) => {
  const index = header.indexOf(name);
  if (index < 0) throw new Error(`Missing column "${name}"`);
  return index;
};
const CATEGORY = column('Categorie');
const LINE = column('Marcă / Gamă');
const SIZE = column('Clasă auto');
const PRICE = column('Preț client (RON)');

const CATEGORIES = {
  'Vinyl Wrap': 'wrap',
  'PPF Transparent': 'ppf',
  'PPF Color': 'ppf-color',
  'PPF Frontal': 'ppf-front',
};
const SIZES = {
  Compactă: 'compact',
  'Sedan / Break': 'sedan',
  SUV: 'suv',
  'SUV mare / Luxury': 'luxury',
};
const slug = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const lines = new Map();
for (const row of rows) {
  const category = CATEGORIES[row[CATEGORY].trim()];
  const size = SIZES[row[SIZE].trim()];
  const price = Number(row[PRICE].trim());
  if (!category) throw new Error(`Unknown category "${row[CATEGORY]}"`);
  if (!size) throw new Error(`Unknown vehicle size "${row[SIZE]}"`);
  if (!Number.isFinite(price) || price <= 0)
    throw new Error(`Invalid price "${row[PRICE]}"`);
  const name = row[LINE].trim();
  const id = slug(name);
  const key = `${category}/${id}`;
  if (!lines.has(key))
    lines.set(key, {
      id,
      category,
      // The row heading already says clear or colour PPF.
      name: name.replace(/\s+(Transparent|Color) PPF$/, ''),
      prices: {},
    });
  lines.get(key).prices[size] = price;
}
for (const line of lines.values())
  for (const size of Object.values(SIZES))
    if (!line.prices[size])
      throw new Error(`${line.category}/${line.id} has no ${size} price`);

const output = `// Generated by scripts/generate-pricing.mjs from the studio price grid.
// Do not edit by hand; update the CSV and rerun the script.
export const PRICE_LINES = ${JSON.stringify([...lines.values()], null, 2)};
`;
writeFileSync('src/price-list.js', output);
console.log(`${lines.size} price lines`);
